"""Namespace-scoped reuse of the installed Controller; preserve its TLS and daemon.

No new controller, daemon, Node, Secret, app configuration or ReplicaSet mutation.
The PodChaos CRD remains installed after a run; never delete global CRDs in cleanup.
"""
import copy
import hashlib
import json
from pathlib import Path
from datetime import datetime, timezone
import tarfile
import time
import yaml
import v3_cdc_fault as f

CONTROLLER='chaos-controller-manager'
ROLE='v3-worker-observe'
ENV={'TARGET_NAMESPACE':'photo','ENABLED_CONTROLLERS':'podchaos','ENABLED_WEBHOOKS':'podchaos'}
API='rbac.authorization.k8s.io/v1'


def fields(d):
    return {'uid':d['metadata']['uid'],'spec':d['spec']}


def controller(k):
    d=k.get('deployment','chaos-mesh',CONTROLLER)
    f.require(d['spec']['replicas']==1 and len(d['spec']['template']['spec']['containers'])==1,'One existing Controller required')
    c=d['spec']['template']['spec']['containers'][0]
    lock=json.loads((f.CHART/'upstream.lock.json').read_text())
    f.require(c['image']==lock['images']['chaos-mesh'] and c['resources']=={
        'requests':{'cpu':'100m','memory':'128Mi'},'limits':{'cpu':'300m','memory':'256Mi'}},'Keep pinned Controller image and resources')
    f.require(not d['spec']['template']['spec'].get('hostNetwork'), 'No host network')
    f.require(d['spec']['template']['spec']['serviceAccountName']==CONTROLLER,'Review changed Controller ServiceAccount')
    return d


def env_map(d):
    return {x['name']:x.get('value') for x in d['spec']['template']['spec']['containers'][0]['env']}


def crd():
    lock=json.loads((f.CHART/'upstream.lock.json').read_text());archive=f.CHART/('chaos-mesh-'+lock['version']+'.tgz')
    f.require(hashlib.sha256(archive.read_bytes()).hexdigest()==lock['sha256'],'Upstream archive checksum mismatch')
    with tarfile.open(archive) as t:
        members=[x for x in t.getmembers() if x.name.endswith('/crds/chaos-mesh.org_podchaos.yaml')]
        f.require(len(members)==1,'Pinned PodChaos CRD missing')
        return yaml.safe_load(t.extractfile(members[0]).read())


def access():
    meta={'name':ROLE,'namespace':'photo','labels':{'yeodam.io/owner':'worker-fault-preparation'}}
    return [{'apiVersion':API,'kind':'Role','metadata':meta,'rules':[
        {'apiGroups':[''],'resources':['pods'],'verbs':['get','list','watch']},
        {'apiGroups':[''],'resources':['events'],'verbs':['get','list','watch','create','patch']},
        {'apiGroups':['chaos-mesh.org'],'resources':['podchaos','podchaos/status','podchaos/finalizers'],'verbs':['get','list','watch','update','patch']}]},
        {'apiVersion':API,'kind':'RoleBinding','metadata':meta,
         'roleRef':{'apiGroup':'rbac.authorization.k8s.io','kind':'Role','name':ROLE},
         'subjects':[{'kind':'ServiceAccount','name':CONTROLLER,'namespace':'chaos-mesh'}]}]


def planned_profile(before):
    value=copy.deepcopy(before)
    env=value['spec']['template']['spec']['containers'][0]['env']
    for key,val in ENV.items():
        entries=[x for x in env if x['name']==key];f.require(len(entries)==1 and 'value' in entries[0], 'Expected explicit Controller environment')
        entries[0]['value']=val
    return value


def profile_plan(k):
    uid=k.identity();d=controller(k)
    f.require(env_map(d).get('TARGET_NAMESPACE')=='kafka' and env_map(d).get('CLUSTER_SCOPED')=='false', 'Start from existing Kafka-only profile')
    f.require(not k.get('networkchaos','kafka')['items'],'No active/pending CDC fault during retargeting')
    hooks=[]
    for kind in ['mutatingwebhookconfiguration','validatingwebhookconfiguration']:
        candidates=[v for v in k.get(kind)['items'] if any(h['name'] in ('mnetworkchaos.kb.io','vnetworkchaos.kb.io') for h in v.get('webhooks',[]))]
        f.require(len(candidates)==1,'Expected one owned webhook configuration of each kind')
        obj=candidates[0];names={x['name'] for x in obj['webhooks']}
        source=[x for x in obj['webhooks'] if x['name'] in ['mnetworkchaos.kb.io','vnetworkchaos.kb.io']]
        f.require(len(source)==1 and not any('podchaos' in n for n in names),'Pod webhook already present; review original profile')
        new=copy.deepcopy(source[0]);prefix='m' if kind.startswith('mutating') else 'v';new['name']=prefix+'podchaos.kb.io'
        # These paths are generated by the same pinned API type, not a new TLS service.
        new['clientConfig']['service']['path']=('/mutate-' if prefix=='m' else '/validate-')+'chaos-mesh-org-v1alpha1-podchaos'
        f.require(new['clientConfig']['service']['namespace']=='chaos-mesh' and new['clientConfig'].get('caBundle'), 'Keep existing public CA and service')
        new['namespaceSelector']={'matchLabels':{'kubernetes.io/metadata.name':'photo'}}
        for rule in new['rules']:rule['resources']=['podchaos']
        new['failurePolicy']='Fail'
        # The server now hosts PodChaos only. Existing Kafka hooks remain registered
        # but no Kafka experiment may be created until the profile is restored.
        hooks.append({'kind':kind,'name':obj['metadata']['name'],'uid':obj['metadata']['uid'],
                      'before':obj['webhooks'],'after':obj['webhooks']+[new]})
    value={'version':1,'clusterUid':uid,'createdAt':f.now(),'controller':fields(d),
           'afterSpec':planned_profile(d)['spec'],'webhooks':hooks,'access':access(),
           'crdSha256':f.sha(crd()),'noGpuOrAppChanges':True}
    return dict(value,planSha256=f.sha(value))


def verify(p,expected):
    f.require(p['planSha256']==expected==f.sha({k:v for k,v in p.items() if k!='planSha256'}), 'Chaos profile Plan hash mismatch')
    f.require(p['crdSha256']==f.sha(crd()) and p['access']==access(),'Changed profile CRD or privileges')
    f.require(len(p['webhooks'])==2 and {h['kind'] for h in p['webhooks']}=={'mutatingwebhookconfiguration','validatingwebhookconfiguration'}, 'Both scoped webhook configurations required')
    for h in p['webhooks']:
        src=[x for x in h['before'] if x['name'] in ['mnetworkchaos.kb.io','vnetworkchaos.kb.io']]
        f.require(len(src)==1,'One original network webhook required')
        new=copy.deepcopy(src[0]);prefix='m' if h['kind'].startswith('mutating') else 'v'
        new['name']=prefix+'podchaos.kb.io'
        new['clientConfig']['service']['path']=('/mutate-' if prefix=='m' else '/validate-')+'chaos-mesh-org-v1alpha1-podchaos'
        new['namespaceSelector']={'matchLabels':{'kubernetes.io/metadata.name':'photo'}}
        for rule in new['rules']:rule['resources']=['podchaos']
        new['failurePolicy']='Fail'
        f.require(h['after']==h['before']+[new], 'Only same-TLS scoped PodChaos webhook may be added')
    d={'metadata':{'uid':p['controller']['uid']},'spec':p['controller']['spec']}
    f.require(planned_profile(d)['spec']==p['afterSpec'] and env_map(d)['TARGET_NAMESPACE']=='kafka','Only reviewed environment change permitted')


def patch_spec(k,p,before,after):
    d=controller(k)
    f.require(d['metadata']['uid']==p['controller']['uid'] and d['spec']==before,'Controller changed; refuse overwrite')
    k.call(['-n','chaos-mesh','patch','deployment',CONTROLLER,'--type=json','-p',json.dumps([
        {'op':'test','path':'/metadata/uid','value':d['metadata']['uid']},
        {'op':'test','path':'/metadata/resourceVersion','value':d['metadata']['resourceVersion']},
        {'op':'test','path':'/spec','value':before},{'op':'replace','path':'/spec','value':after}])])


def patch_hooks(k,h,before,after):
    obj=k.get(h['kind'],name=h['name'])
    f.require(obj['metadata']['uid']==h['uid'] and obj['webhooks']==before,'Webhook changed; refuse overwrite')
    k.call(['patch',h['kind'],h['name'],'--type=json','-p',json.dumps([
        {'op':'test','path':'/metadata/uid','value':h['uid']},
        {'op':'test','path':'/metadata/resourceVersion','value':obj['metadata']['resourceVersion']},
        {'op':'test','path':'/webhooks','value':before},{'op':'replace','path':'/webhooks','value':after}])])


def wait_ready(k,limit=120):
    end=time.monotonic()+limit
    while time.monotonic()<end:
        d=controller(k)
        if d['status'].get('observedGeneration')==d['metadata']['generation'] and d['status'].get('readyReplicas')==1:return
        time.sleep(2)
    raise f.GuardError('Controller not Ready; restore profile before trials')


def apply(k,p,expected,path):
    verify(p,expected);f.require(k.identity()==p['clusterUid'],'Wrong profile cluster')
    f.require(0<=time.time()-datetime.fromisoformat(p['createdAt']).timestamp()<=300,'Refresh profile Plan')
    f.require(fields(controller(k))==p['controller'] and not k.get('networkchaos','kafka')['items'],'Profile changed or CDC experiment active')
    receipt={'plan':p,'crdCreated':False,'resources':[],'hooks':[],'controllerChanged':False,'complete':False}
    # Persist undo journal before each mutation; no read of TLS Secret values.
    def save():
        target=Path(path);tmp=target.with_suffix('.tmp')
        f.require(target.parent.stat().st_mode&0o077==0 and not target.is_symlink() and not tmp.exists(),'Private profile journal required')
        with tmp.open('x') as stream:json.dump(receipt,stream);__import__('os').chmod(tmp,0o600)
        __import__('os').replace(tmp,target)
    f.require(not Path(path).exists(),'Never overwrite profile receipt');save()
    try:
        existing=json.loads(k.call(['get','crd','podchaos.chaos-mesh.org','--ignore-not-found','-o','json']) or '{}')
        if existing:
            f.require(existing['spec']==crd()['spec'],'Review pre-existing different PodChaos CRD')
        else:
            made=f.bounded_json(k.call(['create','-f','-','-o','json'],json.dumps(crd())))
            receipt['crdCreated']=True;receipt['crdUid']=made['metadata']['uid'];save()
        # Wait for discovery / Established before Controller restart, without replacing CRD.
        k.call(['wait','--for=condition=Established','crd/podchaos.chaos-mesh.org','--timeout=45s'],timeout=50)
        for obj in p['access']:
            f.require(not json.loads(k.call(['-n','photo','get',obj['kind'],ROLE,'--ignore-not-found','-o','json']) or '{}'),'Access name already owned elsewhere')
            receipt['resources'].append({'kind':obj['kind'],'name':ROLE,'intent':True});save()
            made=f.bounded_json(k.call(['create','-f','-','-o','json'],json.dumps(obj)))
            receipt['resources'][-1]['uid']=made['metadata']['uid'];save()
        receipt['controllerChanged']=True;save();patch_spec(k,p,p['controller']['spec'],p['afterSpec']);wait_ready(k)
        for h in p['webhooks']:
            receipt['hooks'].append(h['name']);save();patch_hooks(k,h,h['before'],h['after'])
        receipt['complete']=True;save();return receipt
    except BaseException:
        # Restore using the persisted intent even if an API accepted then timed out.
        try:restore(k,receipt)
        finally:save()
        raise


def require_active(k,r):
    p=r['plan'];verify(p,p['planSha256'])
    f.require(r.get('complete') and k.identity()==p['clusterUid'],'Worker profile not fully applied')
    d=controller(k);f.require(d['metadata']['uid']==p['controller']['uid'] and d['spec']==p['afterSpec'],'Photo profile changed')
    f.require(d['status'].get('observedGeneration')==d['metadata']['generation'] and d['status'].get('readyReplicas')==1,'Controller must be Ready')
    for h in p['webhooks']:
        obj=k.get(h['kind'],name=h['name']);f.require(obj['metadata']['uid']==h['uid'] and obj['webhooks']==h['after'],'Worker webhook changed')


def restore(k,r):
    p=r['plan'];verify(p,p['planSha256']);f.require(k.identity()==p['clusterUid'],'Wrong restoration cluster')
    if r.get('controllerChanged') or r.get('complete'):
        f.require(not k.get('podchaos','photo')['items'],'Remove owned PodChaos before profile restoration; never remove another experiment')
    # Reverse only our exact known before/after values. Partial/timed-out writes are inspected.
    for h in reversed(p['webhooks']):
        obj=k.get(h['kind'],name=h['name'])
        f.require(obj['metadata']['uid']==h['uid'],'Restoration webhook UID changed')
        if obj['webhooks']==h['after']:patch_hooks(k,h,h['after'],h['before'])
        else:f.require(obj['webhooks']==h['before'],'Concurrent webhook edit; restore manually')
    d=controller(k)
    if d['spec']==p['afterSpec']:patch_spec(k,p,p['afterSpec'],p['controller']['spec']);wait_ready(k)
    else:f.require(d['metadata']['uid']==p['controller']['uid'] and d['spec']==p['controller']['spec'],'Concurrent Controller edit; restore manually')
    for obj in reversed(p['access']):
        live=json.loads(k.call(['-n','photo','get',obj['kind'],ROLE,'--ignore-not-found','-o','json']) or '{}')
        if not live:continue
        expected=[x for x in r.get('resources',[]) if x['kind']==obj['kind'] and x.get('uid')==live['metadata']['uid']]
        # Unknown UID after a timed-out create requires manual inspection, never adoption.
        same=all(live.get(key)==obj.get(key) for key in ['rules','roleRef','subjects'] if key in obj)
        f.require(expected and same and live['metadata'].get('labels')==obj['metadata']['labels'],'Access restoration ownership mismatch')
        plural='roles' if obj['kind']=='Role' else 'rolebindings'
        k.call(['delete','--raw',f'/apis/{API}/namespaces/photo/{plural}/{ROLE}','-f','-'],
               json.dumps({'apiVersion':'v1','kind':'DeleteOptions','preconditions':{'uid':live['metadata']['uid']}}))
    return {'restored':True,'crdRetained':True,'controllerPodsAdded':0,'daemonNodesAdded':0,'at':f.now()}

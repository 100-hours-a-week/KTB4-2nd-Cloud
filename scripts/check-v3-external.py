#!/usr/bin/env python3
"""Offline ALB Controller and ingress checks. Never print webhook private keys or access AWS."""
import argparse
from collections import Counter
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import subprocess
import yaml

ROOT = Path(__file__).resolve().parents[1]
ACCESS = ROOT / 'deploy/v3/external-access'
CONTROLLER = ROOT / 'deploy/v3/load-balancer-controller'
LOCK = json.loads((CONTROLLER / 'upstream.lock.json').read_text())
ROUTES = json.loads((ACCESS / 'files/routes.json').read_text())
POLICIES = json.loads((ACCESS / 'files/policies.json').read_text())
spec = importlib.util.spec_from_file_location('external_platform', ROOT / 'scripts/check-v3-platform.py')
platform = importlib.util.module_from_spec(spec);spec.loader.exec_module(platform)
require = platform.require


def flatten(documents):
    return [item for d in documents for item in (d['items'] if d['kind'] == 'List' else [d])]


def render_controller(directory):
    archive = Path(directory) / 'load-balancer-controller.tgz'
    require(hashlib.sha256(archive.read_bytes()).hexdigest() == LOCK['sha256'], 'Controller chart checksum mismatch')
    source = subprocess.check_output([os.environ['V3_HELM'], 'template', 'yeodam-v3-load-balancer-controller', str(archive),
              '-n', 'kube-system', '--kube-version', '1.36.0', '--include-crds', '-f', str(CONTROLLER / 'values.yaml')], text=True)
    return flatten(platform.load_documents(source))


def validate_controller(documents):
    expected = {'CustomResourceDefinition':7,'ServiceAccount':1,'Secret':1,'ClusterRole':1,'ClusterRoleBinding':1,
                'Role':1,'RoleBinding':1,'Service':1,'Deployment':1,'MutatingWebhookConfiguration':1,
                'ValidatingWebhookConfiguration':1,'IngressClass':1}
    require(dict(Counter(d['kind'] for d in documents)) == expected, 'Pinned Controller inventory changed')
    deployment = next(d for d in documents if d['kind'] == 'Deployment')
    pod = deployment['spec']['template']['spec'];c = pod['containers'][0]
    require(deployment['spec']['replicas'] == 1 and len(pod['containers']) == 1, 'Minimum Controller1 required')
    require(pod['serviceAccountName'] == 'yeodam-v3-load-balancer-controller' and pod['nodeSelector'] == {'yeodam.io/role':'system'}, 'Use dedicated Pod Identity on existing system Nodes')
    require(c['image'] == LOCK['image'] and c['resources'] == {'requests':{'cpu':'50m','memory':'128Mi'},'limits':{'memory':'256Mi'}}, 'Controller image or resource budget changed')
    expected_args = ['--cluster-name=yeodam-v3-foundation','--ingress-class=yeodam-v3-alb','--aws-region=ap-northeast-2',
                     '--aws-vpc-id=vpc-0ecc3132f3b2170e9','--enable-shield=false','--enable-waf=false','--enable-wafv2=false',
                     '--disable-ingress-class-annotation=true','--enable-backend-security-group=false',
                     '--enable-manage-backend-security-group-rules=false',
                     '--feature-gates=ALBGatewayAPI=false,EnableServiceController=false,GlobalAcceleratorController=false,NLBGatewayAPI=false']
    require(c['args'] == expected_args and c['env'] == [{'name':'AWS_EC2_METADATA_DISABLED','value':'true'}], 'Unreviewed Controller scope or credential fallback')
    require(not pod.get('hostNetwork') and not pod.get('priorityClassName'), 'No host namespace or critical priority preemption')
    ic = next(d for d in documents if d['kind'] == 'IngressClass')
    require(ic['metadata']['name'] == 'yeodam-v3-alb' and not ic['metadata'].get('annotations',{}).get('ingressclass.kubernetes.io/is-default-class'), 'V3 class must not become the default')
    hooks = [d for d in documents if d['kind'] == 'MutatingWebhookConfiguration'][0]['webhooks']
    require(not any(any('services' in rule.get('resources',[]) for rule in h['rules']) for h in hooks), 'Service mutator must remain disabled')
    # Certificate material is generated by the pinned chart; never persisted to CI artifacts.
    tls = next(d for d in documents if d['kind'] == 'Secret')
    require(tls['type'] == 'kubernetes.io/tls' and set(tls['data']) == {'ca.crt','tls.crt','tls.key'}, 'Expected webhook-only TLS Secret')
    for role in [d for d in documents if d['kind'] == 'ClusterRole']:
        require(not any('secrets' in rule.get('resources',[]) for rule in role['rules']), 'Controller cannot read all cluster Secrets')


def controller_schemas(documents):
    for d in documents:
        if d['kind'] == 'CustomResourceDefinition':
            for version in d['spec']['versions']:
                if version.get('served'):
                    target = Path(os.environ['V3_SCHEMA_DIR']) / (d['spec']['names']['kind'].lower() + '.json')
                    target.write_text(json.dumps(version['schema']['openAPIV3Schema']))


def render_access(files=()):
    args = [os.environ['V3_HELM'],'template','yeodam-v3-external-access',str(ACCESS),'--kube-version','1.36.5-eks-577a51e']
    for file in files: args += ['-f',str(file)]
    return subprocess.check_output(args,text=True)


def validate_access(documents, values):
    host=values.get('host',ROUTES['host'])
    require(host in ['v3.yeodam-2gether.com','yeodam-2gether.com'],'Unreviewed public host')
    expected_policies = ([POLICIES['controller']] if values['controllerPolicyEnabled'] else []) + (POLICIES['applications'] if values['ingressEnabled'] else [])
    require(not values['backendRoutesEnabled'] or values['ingressEnabled'], 'Full routes require ingress enabled')
    expected_routes = [route for route in ROUTES['routes'] if values['backendRoutesEnabled'] or route['name'] not in ['trip','photo']] if values['ingressEnabled'] else []
    expected = {('NetworkPolicy',p['namespace'],p['name']) for p in expected_policies} | {('Ingress',r['namespace'],'v3-'+r['name']) for r in expected_routes}
    require(len(documents) == len(expected) and {(d['kind'],d['metadata']['namespace'],d['metadata']['name']) for d in documents} == expected, 'Exact ingress and scoped policy inventory required')
    for d in documents:
        if d['kind'] == 'NetworkPolicy':
            p = next(p for p in expected_policies if (p['namespace'],p['name']) == (d['metadata']['namespace'],d['metadata']['name']))
            require(d['spec'] == p['spec'], 'Network peer or port widened');continue
        route = next(r for r in expected_routes if d['metadata']['name'] == 'v3-'+r['name'])
        annotations = d['metadata']['annotations']
        expected_annotations = {'alb.ingress.kubernetes.io/group.name':ROUTES['group'],'alb.ingress.kubernetes.io/group.order':str(route['order']),
            'alb.ingress.kubernetes.io/load-balancer-name':'yeodam-v3-validation','alb.ingress.kubernetes.io/scheme':'internet-facing',
            'alb.ingress.kubernetes.io/ip-address-type':'ipv4','alb.ingress.kubernetes.io/target-type':'ip',
            'alb.ingress.kubernetes.io/subnets':'subnet-04bfb590e5cf0b665,subnet-02bd8039080de3864',
            'alb.ingress.kubernetes.io/security-groups':values['albSecurityGroupId'],'alb.ingress.kubernetes.io/manage-backend-security-group-rules':'false',
            'alb.ingress.kubernetes.io/certificate-arn':values['certificateArn'],'alb.ingress.kubernetes.io/listen-ports':'[{"HTTP":80},{"HTTPS":443}]',
            'alb.ingress.kubernetes.io/ssl-redirect':'443','alb.ingress.kubernetes.io/ssl-policy':'ELBSecurityPolicy-TLS13-1-2-2021-06',
            'alb.ingress.kubernetes.io/load-balancer-attributes':'idle_timeout.timeout_seconds=120,routing.http.drop_invalid_header_fields.enabled=true'}
        if 'action' in route:
            action = json.loads(annotations['alb.ingress.kubernetes.io/actions.reject'])
            require(action == {'type':'fixed-response','fixedResponseConfig':{'contentType':'application/json','statusCode':str(route['action']),'messageBody':'{"error":"unavailable"}'}}, 'Internal or unknown API denial changed')
            expected_annotations['alb.ingress.kubernetes.io/actions.reject'] = annotations['alb.ingress.kubernetes.io/actions.reject']
            service = {'name':'reject','port':{'name':'use-annotation'}}
        else:
            expected_annotations.update({'alb.ingress.kubernetes.io/healthcheck-protocol':'HTTP','alb.ingress.kubernetes.io/healthcheck-port':route['healthPort'],
                'alb.ingress.kubernetes.io/healthcheck-path':route['health'],'alb.ingress.kubernetes.io/success-codes':'200',
                'alb.ingress.kubernetes.io/target-group-attributes':'deregistration_delay.timeout_seconds=60'})
            service = {'name':route['service'],'port':{'number':route['port']}}
        require(annotations == expected_annotations, 'Unreviewed ALB annotation or target scope')
        require(d['spec'] == {'ingressClassName':'yeodam-v3-alb','rules':[{'host':host,'http':{'paths':[{'path':p,'pathType':t,'backend':{'service':service}} for p,t in route['paths']]}}]}, 'Ingress host, path or namespace target changed')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--controller-directory',type=Path)
    parser.add_argument('-f',action='append',default=[])
    parser.add_argument('--output',type=Path)
    args = parser.parse_args()
    if args.controller_directory:
        docs = render_controller(args.controller_directory);validate_controller(docs);controller_schemas(docs)
        safe = [d for d in docs if d['kind'] not in ['Secret','CustomResourceDefinition']]
        source = yaml.safe_dump_all(safe);platform.schema_check(source)
        if args.output: args.output.write_text(source)
        print('Pinned Controller checked; webhook private TLS material excluded from output. No cluster accessed.')
    else:
        values = yaml.safe_load((ACCESS/'values.yaml').read_text())
        for file in args.f: values.update(platform.load_documents(Path(file).read_text())[0])
        source = render_access(args.f);validate_access(platform.load_documents(source),values);platform.schema_check(source)
        if args.output: args.output.write_text(source)
        print('V3 external access checked; no ALB, DNS or workload created.')


if __name__ == '__main__': main()
